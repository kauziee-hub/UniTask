    ("How is this different from Teams or Moodle?", "Those hold the assignments. UniTask combines them, decides what to do first, plans the time, and teaches the content. It never submits on the student's behalf."),
    ("Can it read my Teams without permission?", "No. The student signs in on Microsoft's own page and grants read-only access. If the college requires admin approval, UniTask shows that clearly instead of working around it."),
    ("Does it predict exam questions?", "No. It shows how often topics appeared in the student's own past papers. That's history used for prioritising, and the app labels it that way."),
