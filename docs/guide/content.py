STACK = [
    ("Web app and API", "One container on **Amazon ECS** (Fargate, HTTPS load balancer) serving the React site and the FastAPI API."),
    ("Database", "**Amazon RDS for PostgreSQL**, with versioned Alembic migrations. SQLite for local development."),
    ("Files", "**Amazon S3**: private bucket, encrypted, with 5-minute presigned download links."),
    ("AI", "**Amazon Bedrock** when enabled, with **Google Gemini** as fallback. Used to explain, structure and tutor; never to decide deadlines or feasibility."),
    ("OCR", "**Amazon Textract** for scanned pages and photos (or the vision model)."),
    ("Reminders and email", "**Amazon EventBridge** schedules → reminder job → **Amazon SES** email digest."),
    ("Accounts", "Local accounts or **Amazon Cognito** user pool."),
    ("Monitoring", "**Amazon CloudWatch** logs from the container. Budget alerts at $5 / $15 / $30."),
    ("Integrations", "**Microsoft Graph** (Teams Education, read-only, delegated), Moodle iCalendar feeds, VTOP extension."),
]

